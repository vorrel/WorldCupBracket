// Generates a single SQL transaction that upserts teams + matches into
// Supabase. Run from repo root:
//
//   node scripts/print-seed-sql.mjs > seed.sql
//
// The output is idempotent (uses ON CONFLICT DO UPDATE) so re-running is safe.

import { TEAMS } from '../src/data/teams.ts'
import { MATCHES } from '../src/data/matches.ts'

function q(v) {
  if (v === undefined || v === null) return 'NULL'
  if (typeof v === 'number') return String(v)
  return `'${String(v).replace(/'/g, "''")}'`
}

console.log('-- Auto-generated by scripts/print-seed-sql.mjs')
console.log('begin;')

console.log('\n-- Teams ---------------------------------------------------------')
console.log('insert into public.teams (code, name, group_letter, flag) values')
console.log(
  TEAMS
    .map(t => `  (${q(t.code)}, ${q(t.name)}, ${q(t.group)}, ${q(t.flag)})`)
    .join(',\n'),
)
console.log(`on conflict (code) do update set
  name = excluded.name,
  group_letter = excluded.group_letter,
  flag = excluded.flag;`)

console.log('\n-- Matches -------------------------------------------------------')
console.log(`insert into public.matches (
  match_number, round, group_letter, kickoff_at,
  team_a_code, team_b_code, slot_a_label, slot_b_label,
  feeds_from_a, feeds_from_b
) values`)
console.log(
  MATCHES
    .map(m => `  (${q(m.matchNumber)}, ${q(m.round)}, ${q(m.group)}, ${q(m.kickoffAt)}, ${q(m.teamA)}, ${q(m.teamB)}, ${q(m.slotALabel)}, ${q(m.slotBLabel)}, ${q(m.feedsFromA)}, ${q(m.feedsFromB)})`)
    .join(',\n'),
)
console.log(`on conflict (match_number) do update set
  round = excluded.round,
  group_letter = excluded.group_letter,
  kickoff_at = excluded.kickoff_at,
  team_a_code = excluded.team_a_code,
  team_b_code = excluded.team_b_code,
  slot_a_label = excluded.slot_a_label,
  slot_b_label = excluded.slot_b_label,
  feeds_from_a = excluded.feeds_from_a,
  feeds_from_b = excluded.feeds_from_b;`)

console.log('\ncommit;')
